#include "tp_signed_manifest.h"
#include <assert.h>
#include <string.h>
static uint8_t image[]="abc";
static bool fail_read;
static tp_result read_image(void *ctx,uint8_t bank,uint32_t off,void *out,size_t n) {
    (void)ctx; if (fail_read) return TP_IO_ERROR;
    assert(bank==1 && off<=3 && n<=3-off); memcpy(out,image+off,n); return TP_OK;
}
static void hex(const char *s,uint8_t *out,size_t n) {
    for(size_t i=0;i<n;i++) {
        unsigned x=0;
        for(unsigned j=0;j<2;j++) { char c=*s++; x=x*16+(unsigned)(c<='9'?c-'0':c-'a'+10); }
        out[i]=(uint8_t)x;
    }
}
int main(void) {
    /* P-256 key and signature generated by Python cryptography for "abc".
     * The private key is public test data and must never be used on devices. */
    const char *key="6780c5fc70275e2c7061a0e7877bb174deadeb9887027f3fa83654158ba7f50c3cba8c34bc35d20e81f730ac1c7bd6d661a942f90c6a9ca55c512f9e4a001266";
    const char *signed_hex="5450553178563412020000000300000001000000ba7816bf8f01cfea414140de5dae2223b00361a396177a9cb410ff61f20015adad628c012e2dd70b93c667ef7166ff7dbf199f87e4105fbf15f89ba483f0e7f169b5287eedeef89d4a6299c0fc066a9a94b7418f92722a08f81f22d5b9f12679";
    tp_signed_manifest ctx={0}; tp_download_manifest m; uint8_t data[116];
    hex(key,ctx.public_key,64); hex(signed_hex,data,116);
    ctx.product_id=0x12345678u; ctx.image=(tp_image_hash_io){NULL,read_image,{3,3}};
    assert(tp_signed_manifest_authenticate(&ctx,data,sizeof(data),&m)==TP_OK);
    assert(m.bank==1 && m.version==2 && m.size==3);
    assert(tp_signed_manifest_verify_image(&ctx,&m)==TP_OK);
    image[0]^=1; assert(tp_signed_manifest_verify_image(&ctx,&m)==TP_INVALID); image[0]^=1;
    fail_read=true; assert(tp_signed_manifest_verify_image(&ctx,&m)==TP_IO_ERROR); fail_read=false;
    m.id[0]^=1; assert(tp_signed_manifest_verify_image(&ctx,&m)==TP_INVALID); m.id[0]^=1;
    data[52]^=1; assert(tp_signed_manifest_authenticate(&ctx,data,sizeof(data),&m)==TP_INVALID);
    assert(!ctx.ready && tp_signed_manifest_verify_image(&ctx,&m)==TP_INVALID); data[52]^=1;
    data[8]^=1; assert(tp_signed_manifest_authenticate(&ctx,data,sizeof(data),&m)==TP_INVALID); data[8]^=1;
    ctx.product_id++; assert(tp_signed_manifest_authenticate(&ctx,data,sizeof(data),&m)==TP_INVALID); ctx.product_id--;
    ctx.image.capacity[1]=2; assert(tp_signed_manifest_authenticate(&ctx,data,sizeof(data),&m)==TP_INVALID); ctx.image.capacity[1]=3;
    assert(tp_signed_manifest_authenticate(&ctx,data,sizeof(data)-1,&m)==TP_INVALID);
    assert(tp_signed_manifest_authenticate(&ctx,data,sizeof(data),&m)==TP_OK);
    memset(ctx.public_key,0,64); assert(tp_signed_manifest_authenticate(&ctx,data,sizeof(data),&m)==TP_INVALID);
    return 0;
}
